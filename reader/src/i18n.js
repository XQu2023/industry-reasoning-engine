export function t(locale) {
  const code = locale === "zh" ? "zh" : "en";
  const base = UI_BASE[code] ?? UI_BASE.en;
  return {
    ...base,
    brand: getBrandMark(code),
    footer: withBrandFooter(code, base.footerRest),
  };
}

/** @deprecated Prefer t(locale); kept for any direct UI_BASE access in tests. */
export const UI = new Proxy(
  {},
  {
    get(_target, prop) {
      if (prop === "en" || prop === "zh") return t(prop);
      return undefined;
    },
  },
);

export function localizeConfidence(value, locale) {
  const ui = t(locale);
  const key = String(value ?? "").trim() || "—";
  return ui.confidence[key] ?? key;
}

export function localizeReadingTime(value, locale) {
  if (locale !== "zh") return value || t("en").readingTimeFallback;
  if (!value) return t("zh").readingTimeFallback;
  const match = String(value).match(/(\d+)/);
  if (match) return `约 ${match[1]} 分钟`;
  if (/分钟/.test(value)) return value;
  return t("zh").readingTimeFallback;
}
